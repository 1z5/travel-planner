import { describe, expect, it } from "vitest";
import { warnTag } from "@/lib/warn-tag";

// warnTag 把一条长文本预警归成短标签（PlanView 用来给预警上分类徽章）。
// 特征短语来自 validate.ts 生成的预警文本——每条分类钉一条，再加「匹配不上
// 返回 null」的优雅降级。

describe("warnTag 预警分类", () => {
  it("绕路", () => {
    expect(warnTag("第 1 天站点间通勤约 2 小时 54 分钟，偏长，可能存在绕路，建议合并同区域景点")).toBe("绕路");
  });

  it("节奏（超上限 + 偏松两种）", () => {
    expect(warnTag("第 1 天安排约 13 小时，超出适中节奏上限（10 小时），可删减 1 个景点")).toBe("节奏");
    expect(warnTag("第 2 天安排约 4 小时，偏松，可加一个景点或放慢节奏")).toBe("节奏");
  });

  it("预算（超支 + 宽松两种）", () => {
    expect(warnTag("行程合计人均约 5000 元，超出预算 4000 元 25%，注意控制")).toBe("预算");
    expect(warnTag("预算较为宽松：合计人均约 2000 元，用掉预算 3000 元的 67%")).toBe("预算");
  });

  it("区域分散", () => {
    expect(warnTag("第 3 天的 5 个景点分散在 5 个不同区域（A、B、C、D、E），通勤与折返可能明显增加")).toBe("分散");
  });

  it("覆盖（境外两种文案，且必须先于未验真判定）", () => {
    // 主提示里同时含「境外」和「未在高德检索到」——必须先归覆盖（实测踩过的顺序 bug）
    expect(warnTag("「京都」疑似境外或无 POI 覆盖的目的地：9 个景点/餐厅全部未在高德检索到。本产品的 POI 验真与通勤估算依赖高德")).toBe("覆盖");
    expect(warnTag("未检索到的地点包括：清水寺 等 9 个，均为境外/无覆盖数据所致")).toBe("覆盖");
  });

  it("未验真（单点未命中，不含「境外」）", () => {
    expect(warnTag("第 1 天「桃花源记」未在高德检索到，可能名称有误或已关闭，出发前请自行确认")).toBe("未验真");
  });

  it("活动", () => {
    expect(warnTag("重点活动「测试音乐会」被排在 20:00 开始，晚于活动时间 19:00，可能错过开场")).toBe("活动");
  });

  it("系统（高德波动 + 通勤估算失败）", () => {
    expect(warnTag("高德服务波动：3 个地点本次未能验真，POI 核查不完整")).toBe("系统");
    expect(warnTag("第 1 天通勤估算失败（高德服务波动），当天的通勤与节奏体检已跳过")).toBe("系统");
  });

  it("匹配不上 → null（优雅降级，不加假标签）", () => {
    expect(warnTag("这是一条未来新增的、无法归类的预警")).toBeNull();
    expect(warnTag("")).toBeNull();
  });
});
